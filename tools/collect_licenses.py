"""Collect the licence texts of every third-party component VektorFIL ships with.

    python tools/collect_licenses.py      -> writes THIRD_PARTY_LICENSES.txt

The texts are taken from the installed packages' own metadata (dist-info), so they are
exactly the ones of the versions being distributed.  Run this before every release build.
"""
import sys
import importlib.metadata as md
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# (distribution name, short description, licence family)
COMPONENTS = [
    ("PySide6", "Qt for Python bindings", "LGPLv3"),
    ("PySide6_Essentials", "Qt libraries (essentials)", "LGPLv3"),
    ("PySide6_Addons", "Qt libraries (add-ons)", "LGPLv3"),
    ("shiboken6", "Qt for Python binding runtime", "LGPLv3"),
    ("numpy", "numerical arrays (bundles OpenBLAS and compiler runtimes)", "BSD-3-Clause"),
    ("scipy", "scientific routines (bundles OpenBLAS and compiler runtimes)", "BSD-3-Clause"),
    ("mpmath", "arbitrary-precision arithmetic", "BSD-3-Clause"),
    ("pyqtgraph", "plotting", "MIT"),
]

HEADER = """VektorFIL -- third-party software notices
==========================================

VektorFIL itself is Copyright (C) 2026 Pieter Ibelings and licensed under the GNU General
Public License v3 or later (see LICENSE).  It is built with the components listed below,
each under its own licence; their licence texts follow in full.

Qt / PySide6 (LGPLv3): the Qt and PySide6 libraries are distributed as separate,
unmodified shared libraries (DLL / .pyd files) in the program folder and may be replaced by
compatible versions.  Their source code is available from https://download.qt.io/ and
https://code.qt.io/ (Qt) and https://pypi.org/project/PySide6/ (PySide6).

The program is compiled with Nuitka (https://nuitka.net, Apache License 2.0); code
generated by Nuitka is not subject to Nuitka's licence.

"""


def licence_texts(dist_name):
    """All licence/copying/notice files of an installed distribution."""
    try:
        dist = md.distribution(dist_name)
    except md.PackageNotFoundError:
        return None, []
    texts = []
    for f in dist.files or []:
        name = f.name.lower()
        if any(k in name for k in ("license", "licence", "copying", "notice")) and not name.endswith(".py"):
            p = Path(dist.locate_file(f))
            if p.is_file() and p.stat().st_size < 2_000_000:
                texts.append((str(f), p.read_text(encoding="utf-8", errors="replace")))
    return dist.version, texts


def main():
    out = [HEADER]
    out.append("Components:\n")
    found = []
    for dist, what, fam in COMPONENTS:
        ver, texts = licence_texts(dist)
        if ver is None:
            continue
        found.append((dist, ver, texts))
        out.append(f"  * {dist} {ver} -- {what} -- {fam}\n")
    pyver = ".".join(map(str, sys.version_info[:3]))
    out.append(f"  * Python {pyver} runtime -- PSF License\n\n")
    for dist, ver, texts in found:
        for fname, text in texts:
            out.append("\n" + "=" * 78 + f"\n{dist} {ver}: {fname}\n" + "=" * 78 + "\n\n")
            out.append(text.strip() + "\n")
    psf = Path(sys.base_prefix) / "LICENSE.txt"
    if psf.exists():
        out.append("\n" + "=" * 78 + f"\nPython {pyver}: LICENSE.txt\n" + "=" * 78 + "\n\n")
        out.append(psf.read_text(encoding="utf-8", errors="replace").strip() + "\n")
    target = ROOT / "THIRD_PARTY_LICENSES.txt"
    target.write_text("".join(out), encoding="utf-8")
    print(f"wrote {target} ({target.stat().st_size // 1024} kB, {len(found)} packages)")


if __name__ == "__main__":
    main()
